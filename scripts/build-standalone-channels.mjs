/** Generate the standalone business artifact from the published channel pack; platform interface replacements must match exactly. */
import fs from 'node:fs'
import crypto from 'node:crypto'

const source = fs.readFileSync(new URL('../vendor/channel-pack/pack.js', import.meta.url), 'utf8')
let output = source
function replaceOnce(from, to) {
  if (output.split(from).length !== 2) throw new Error(`Standalone channel generation site is not unique or has changed: ${from.slice(0, 90)}`)
  output = output.replace(from, to)
}
// The standalone app does not register the host settings form, so delete the two schemas used only by the host.
output = output.replace(/^import Schema2? from "@deepseek-ai\/schemastery";\r?\n/gm, '')
replaceOnce(output.match(/var channelPackSchema = Schema\.object\(\{[\s\S]*?\n\}\);/)?.[0] ?? 'missing schema', 'var channelPackSchema;')
replaceOnce(output.match(/var Config = Schema2\.object\(\{[\s\S]*?\n\}\);/)?.[0] ?? 'missing config', 'var Config;')
output = output.replace(/from "@deepseek-ai\/(?:cordis|dsh-credentials|dsh-llm)"/g, 'from "./contracts.mjs"')
replaceOnce(output.match(/function resolveChannelPackHome\(ctx\) \{[\s\S]*?\n\}/)?.[0] ?? 'missing home resolver',
  'function resolveChannelPackHome(ctx) {\n  if (typeof ctx.platform?.channelHome !== "string") throw new Error("Standalone channel is missing its data directory");\n  return ctx.platform.channelHome;\n}')
replaceOnce('  mountOpenAiGateway(ctx, pool);\n  installLoopResume(ctx);', '  // The standalone service gets a unified gateway from the outer layer; the automatic loop resume of the host agent has no corresponding service.')
replaceOnce('resolve(dirname(fileURLToPath(import.meta.url)), "qoder-auth-wasm.wasm")', 'fileURLToPath(new URL("../../../vendor/channel-pack/qoder-auth-wasm.wasm", import.meta.url))')
replaceOnce('export {\n  Config,', `export {
  toGenerateOptions, toResponsesGenerateOptions, normalizeReasoningEffort,
  responsesReasoningEffort, normalizeMaxTokens, responsesMaxOutputTokens,
  markGatewayChannel,
  collectGatewayModels, collectGatewayEffortViews, toOpenAiModels,
  Config,`)
if (/@deepseek-ai\/.*["'];/.test(output)) throw new Error('The standalone artifact still contains a host import')
output = `// Generated by scripts/build-standalone-channels.mjs — do not edit by hand.\n// Original channel pack SHA256: ${crypto.createHash('sha256').update(source).digest('hex')}\n${output}`
const file = new URL('../packages/standalone/channels/business.mjs', import.meta.url)
if (process.argv.includes('--check')) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== output) throw new Error('The standalone channel artifact needs to be regenerated')
} else {
  fs.mkdirSync(new URL('../packages/standalone/channels/', import.meta.url), { recursive: true })
  fs.writeFileSync(file, output)
}
console.log('Standalone channel artifact verified')
